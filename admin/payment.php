<?php
/**
 * Single payment: full details, access link management and audit timeline.
 */
require_once __DIR__ . '/../config.php';

$admin = app()->auth->requireLogin();
$settings = app()->settings->all();

$id = query_int('id');
if ($id <= 0) {
    abort(404, 'Payment not found.');
}

$payment = app()->payments->find($id);
if (!$payment) {
    abort(404, 'Payment not found.');
}

if (is_post()) {
    csrf_verify();
    $action = post_str('action');

    if ($action === 'regenerate') {
        if ($payment['status'] !== Payments::STATUS_SUCCESS) {
            flash('danger', 'Access can only be issued for successful payments.');
            redirect('admin/payment.php?id=' . $id);
        }

        $days = (int) post_str('days', (string) app()->settings->accessDays());
        if ($days < 0 || $days > 3650) {
            $days = app()->settings->accessDays();
        }

        $access = app()->payments->grantAccess($id, $days);
        app()->payments->logEvent(
            $id,
            'access.regenerated',
            'Access link regenerated by ' . $admin['username'] . ($days > 0 ? ' for ' . $days . ' days' : ' (no expiry)')
        );
        app_log('info', 'Access link regenerated', ['payment_id' => $id, 'admin_id' => $admin['id'], 'days' => $days]);

        flash('success', $access['expires_at'] === null
            ? 'A new access link was generated. It never expires.'
            : 'A new access link was generated, valid until ' . date_display($access['expires_at']) . '.');
        redirect('admin/payment.php?id=' . $id);
    }

    flash('danger', 'Unknown action.');
    redirect('admin/payment.php?id=' . $id);
}

$payment = app()->payments->find($id);
$token = isset($payment['access_token']) ? (string) $payment['access_token'] : '';

render('admin/payment', [
    'pageTitle'  => 'Payment #' . $id,
    'activeNav'  => 'payments.php',
    'admin'      => $admin,
    'settings'   => $settings,
    'payment'    => $payment,
    'events'     => app()->payments->events($id),
    'accessLink' => $token !== '' ? url('success.php?t=' . urlencode($token)) : url('success.php'),
    'videos'     => catalog_videos_for_payment($payment),
]);
